export function CompatibilityIntelligence({ view = 'simple', onViewChange = () => {} }) {
  const [first, setFirst] = useState('Catering');
  const [second, setSecond] = useState('Photography');
  const categories = [...new Set([...SERVICES.map(([name]) => name), ...rules.flatMap((item) => [item.service_1, item.service_2])])];
  const selected = rules.find((item) =>
    (item.service_1 === first && item.service_2 === second) ||
    (item.service_1 === second && item.service_2 === first));
  return <>
    <PageHeader eyebrow="RESEARCH DEMO / COMPATIBILITY" title="How services fit together"
      description="Explore the recorded scores for pairs of service categories used in package recommendations."
      actions={<ResearchViewToggle view={view} onViewChange={onViewChange}/>}/>
    <section className="card compatibility-intro" aria-labelledby="compatibility-intro-title">
      <h2 id="compatibility-intro-title">What does a compatibility score mean?</h2>
      <p>Some event services may be easier to plan together than others. This research matrix gives each recorded pair of <strong>service categories</strong> a score out of 100. It is a planning rule, not evidence that two named vendors have worked together.</p>
      <p>For an event requiring the same service categories, every package can receive the same category-pair score even when its vendors differ. Unlisted pairs have an unknown score.</p>
    </section>
    <section className="card compatibility-explorer" aria-labelledby="pair-explorer-title">
      <div className="explorer-heading"><div><p className="eyebrow">EXPLORE A PAIR</p><h2 id="pair-explorer-title">Choose two services</h2></div>
        <Badge>{rules.length} recorded matrix rows</Badge></div>
      <div className="pair-fields">
        <label htmlFor="service-pair-first">First service
          <select id="service-pair-first" value={first} onChange={(event) => setFirst(event.target.value)}>
            {categories.map((name) => <option key={name} value={name}>{name}</option>)}
          </select>
        </label>
        <label htmlFor="service-pair-second">Second service
          <select id="service-pair-second" value={second} onChange={(event) => setSecond(event.target.value)}>
            {categories.map((name) => <option key={name} value={name}>{name}</option>)}
          </select>
        </label>
      </div>
      <div className="pair-result" aria-live="polite" aria-atomic="true">
        <span className="pair-result-label">{first} + {second}</span>
        {selected ? <>
          <strong className="pair-score">{selected.base_score}<small> / 100</small></strong>
          <div className="pair-progress"><ProgressBar value={selected.base_score}/></div>
          <p>The source matrix records {selected.base_score} out of 100 for this category pair. This is a category-level planning heuristic; real vendor collaboration has not been verified.</p>
          {first === second && <p>Same-category entries are present in the source matrix. Normal package requests use distinct required services, so this entry usually does not contribute to a package score.</p>}
        </> : <>
          <strong className="pair-unknown">Unknown score</strong>
          <p>No rule is recorded for this pair. It remains unknown; the explorer does not assign a substitute score or assume that vendors collaborate.</p>
        </>}
      </div>
    </section>
    <details className="card research-disclosure" key={view} open={view === 'research'}>
      <summary>Advanced Research Details <span>Complete source matrix · {rules.length} rows</span></summary>
      <div className="research-disclosure-body">
        <p>The values below are the complete bundled copy of <code>vendor_compatibility_matrix.csv</code>. Pair order does not change the score. The matrix describes categories, not observed relationships between vendor businesses.</p>
        <div className="table-scroll"><table className="data-table"><caption>All {rules.length} recorded service-category pairs</caption>
          <thead><tr><th scope="col">Service A</th><th scope="col">Service B</th><th scope="col">Base score</th><th scope="col">Evidence</th></tr></thead>
          <tbody>{rules.map((item) => <tr key={item.service_1 + '|' + item.service_2}>
            <td>{item.service_1}</td><td>{item.service_2}</td><td><strong>{score(item.base_score)}</strong></td>
            <td>Category rule; vendor collaboration unverified</td>
          </tr>)}</tbody></table></div>
      </div>
    </details>
  </>;
}
